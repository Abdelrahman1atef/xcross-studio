/// How xcross builds a plugin.
enum PluginKind {
  /// The plugin ships its own Swift package.
  swiftpm('swiftpm'),

  /// An override xcross drafted (its first line says so).
  draft('draft'),

  /// An override the developer wrote.
  handWritten('hand_written'),

  /// Only a podspec: the next build drafts it.
  podspecOnly('podspec_only'),

  /// No native iOS code.
  noIosCode('no_ios_code');

  const PluginKind(this.wire);

  final String wire;
}

/// One thing wrong with a plugin, or to look at.
final class PluginProblem {
  const PluginProblem(this.code, this.message);

  /// `stale`, `manifest_missing`, `unknown_pods`, `review_pending`.
  final String code;
  final String message;

  Map<String, Object?> toJson() => {'code': code, 'message': message};
}

/// A plugin as `plugin status` reports it.
final class PluginStatus {
  const PluginStatus({
    required this.name,
    required this.kind,
    this.version,
    this.overridePath,
    this.problems = const [],
    this.edited = false,
  });

  final String name;
  final String? version;
  final PluginKind kind;

  /// The override folder in use, relative to the project, with `/`.
  final String? overridePath;
  final List<PluginProblem> problems;

  /// The draft differs from what xcross would write now: a hand edit, or a
  /// draft from an older xcross.
  final bool edited;

  /// What the developer can do about it: `regenerate` (xcross rewrites the
  /// draft, after a backup), `review` (look at the draft, then `plugin ack`),
  /// `manual` (xcross cannot do it), or null when there is nothing to do.
  String? get action {
    if (problems.isEmpty) return null;
    final needsFix = problems.any(
      (p) =>
          p.code == 'stale' ||
          p.code == 'manifest_missing' ||
          p.code == 'permission_macros_missing',
    );
    if (needsFix) return kind == PluginKind.draft ? 'regenerate' : 'manual';
    if (problems.any((p) => p.code == 'review_pending')) return 'review';
    return 'manual';
  }

  /// xcross may overwrite this plugin's override (only drafts, never a file
  /// the developer wrote).
  bool get canRegenerate => kind == PluginKind.draft;

  /// The CLI command that does [action], or null.
  List<String>? get command => switch (action) {
    'regenerate' => ['plugin', 'shim', name, '--force'],
    'review' => ['plugin', 'ack', name],
    _ => null,
  };

  Map<String, Object?> toJson() => {
    'name': name,
    'version': version,
    'kind': kind.wire,
    'overridePath': overridePath,
    'edited': edited,
    'problems': [for (final p in problems) p.toJson()],
    'action': action,
    'canRegenerate': canRegenerate,
    'command': command,
  };
}

/// The first line xcross writes into a Package.swift draft.
const draftMarkerLine = '// DRAFT generated by `xcross plugin shim`';

/// Reads every iOS plugin of [project].
List<PluginStatus> readPluginStatus(
  ProjectPlugins plugins,
  String project, {
  DraftLedger? ledger,
}) {
  final fs = plugins.fileSystem;
  final paths = plugins.paths;
  final writer = PluginDraftWriter(plugins);
  final base = paths.join(project, 'xcross_overrides');
  final records = (ledger ?? DraftLedger(fs, paths, base)).read();
  final result = <PluginStatus>[];

  for (final plugin in plugins.read(project)) {
    final root = paths.join(base, plugin.name);
    final version = plugin.version;
    String? folder;
    var otherVersions = <String>[];
    if (fs.directory(root).existsSync()) {
      final exact = version == null ? null : paths.join(root, version);
      if (exact != null &&
          fs.file(paths.join(exact, 'Package.swift')).existsSync()) {
        folder = exact;
      } else if (fs.file(paths.join(root, 'Package.swift')).existsSync()) {
        folder = root;
      } else {
        otherVersions = [
          for (final entity in fs.directory(root).listSync())
            if (fs.file(paths.join(entity.path, 'Package.swift')).existsSync())
              paths.basename(entity.path),
        ]..sort();
      }
    }

    if (folder == null && fs.directory(root).existsSync()) {
      // A folder that does not apply: the plugin was upgraded.
      final shown = otherVersions.isEmpty
          ? 'no Package.swift'
          : 'for ${otherVersions.join(', ')}';
      final draft = otherVersions.isEmpty
          ? null
          : isDraftManifest(
              fs,
              paths.join(root, otherVersions.last, 'Package.swift'),
            );
      result.add(
        PluginStatus(
          name: plugin.name,
          version: version,
          kind: draft == false ? PluginKind.handWritten : PluginKind.draft,
          overridePath: 'xcross_overrides/${plugin.name}',
          problems: [
            PluginProblem(
              'stale',
              'The override in xcross_overrides/${plugin.name} is $shown, but '
                  'the project now uses ${plugin.name} ${version ?? '?'}, so '
                  'a build skips it.',
            ),
          ],
        ),
      );
      continue;
    }

    if (folder != null) {
      final manifest = paths.join(folder, 'Package.swift');
      final isDraft = isDraftManifest(fs, manifest);
      final relative = paths
          .relative(folder, from: project)
          .replaceAll(r'\', '/');
      final problems = <PluginProblem>[];
      var edited = false;
      if (isDraft && plugins.hasPodspec(plugin)) {
        try {
          final spec = Podspec.parse(
            fs.file(plugins.podspecPath(plugin)).readAsStringSync(),
          );
          final macros = writer.macrosFor(plugin, project);
          final fresh = draftPackageSwift(
            plugin: plugin.name,
            spec: spec,
            files: plugins.platformFiles(plugin),
            pluginVersion: version,
            defines: macros,
          );
          final written = fs.file(manifest).readAsStringSync();
          final off = [
            for (final MapEntry(:key, :value) in macros.entries)
              if (value == '1' && !written.contains('.define("$key"')) key,
          ];
          if (off.isNotEmpty) {
            problems.add(
              PluginProblem(
                'permission_macros_missing',
                'The draft does not switch on '
                    '${off.map((m) => m.replaceFirst('PERMISSION_', '').toLowerCase()).join(', ')}, '
                    'so ${plugin.name} answers "denied" without asking, although '
                    'Info.plist or the Podfile declares it.',
              ),
            );
          }
          edited = written.trim() != fresh.text.trim();
          final missing = [
            for (final target in fresh.resourceCopies.values)
              if (!fs
                  .file(paths.joinAll([folder, ...target.split('/')]))
                  .existsSync())
                target,
          ];
          if (missing.isNotEmpty) {
            problems.add(
              PluginProblem(
                'manifest_missing',
                'The draft lacks ${missing.join(', ')}, which ${plugin.name} '
                    'ships; App Store Connect warns about a missing privacy '
                    'manifest.',
              ),
            );
          }
          // ignore: avoid_catches_without_on_clauses
        } catch (_) {
          // A podspec the drafter cannot read is reported by `plugin check`.
        }
      }
      final record =
          records[DraftLedger.key(plugin.name, version)] ??
          records[DraftLedger.key(plugin.name, null)];
      if (isDraft && record != null && !record.reviewed) {
        problems.add(
          PluginProblem(
            'review_pending',
            'xcross wrote this draft on ${record.writtenAt.split('T').first}; '
                'look it over, then mark it reviewed.',
          ),
        );
      }
      result.add(
        PluginStatus(
          name: plugin.name,
          version: version,
          kind: isDraft ? PluginKind.draft : PluginKind.handWritten,
          overridePath: relative,
          problems: problems,
          edited: edited,
        ),
      );
      continue;
    }

    if (plugins.hasSwiftPackage(plugin)) {
      result.add(
        PluginStatus(
          name: plugin.name,
          version: version,
          kind: PluginKind.swiftpm,
        ),
      );
    } else if (!plugins.hasPodspec(plugin)) {
      result.add(
        PluginStatus(
          name: plugin.name,
          version: version,
          kind: PluginKind.noIosCode,
        ),
      );
    } else {
      final unknown = writer.unknownPods(plugin);
      result.add(
        PluginStatus(
          name: plugin.name,
          version: version,
          kind: PluginKind.podspecOnly,
          problems: [
            if (unknown.isNotEmpty)
              PluginProblem(
                'unknown_pods',
                'A build leaves out the native code of ${plugin.name}: no Swift '
                    'package is known for ${unknown.join(', ')}.',
              ),
          ],
        ),
      );
    }
  }
  return result;
}

/// Whether the Package.swift at [manifest] is a draft xcross wrote (its header
/// says so; a developer's own file does not).
bool isDraftManifest(HostFileSystemInterface fs, String manifest) {
  final file = fs.file(manifest);
  if (!file.existsSync()) return false;
  return file
      .readAsStringSync()
      .split('\n')
      .take(4)
      .any((line) => line.trim().startsWith(draftMarkerLine));
}

/// `xcross plugin status [--project <dir>] [--json]`.
final class PluginStatusCommand extends Command<void> {
  PluginStatusCommand({required this.plugins, required this.write}) {
    argParser
      ..addOption('project', defaultsTo: '.', help: 'Flutter project folder.')
      ..addFlag('json', negatable: false, help: 'Print one JSON object.');
  }

  final ProjectPlugins plugins;
  final void Function(String) write;

  @override
  String get name => 'status';

  @override
  String get description =>
      'What each iOS plugin needs from you: a stale or incomplete override, a '
      'draft to review, a plugin a build would leave out.';

  @override
  Future<void> run() async {
    final project = argResults!.option('project')!;
    try {
      final all = readPluginStatus(plugins, project);
      if (argResults!.flag('json')) {
        write(
          '${jsonEncode({
            'v': 1,
            'type': 'plugin_status',
            'project': project,
            'plugins': [for (final s in all) s.toJson()],
          })}\n',
        );
        return;
      }
      final out = StringBuffer();
      for (final status in all) {
        final label = '${status.name} ${status.version ?? ''}'.trimRight();
        out.writeln(
          '${status.problems.isEmpty ? '✔' : '!'} $label  (${status.kind.wire})',
        );
        for (final problem in status.problems) {
          out.writeln('    ${problem.code}: ${problem.message}');
        }
        if (status.command case final command?) {
          out.writeln('    fix: xcross ${command.join(' ')}');
        }
      }
      if (all.isEmpty) out.writeln('No iOS plugins.');
      write(out.toString());
    } on PluginFailure catch (failure) {
      throw failure.toCliError();
    }
  }
}

/// `xcross plugin ack <plugin>`: the draft was looked at.
final class PluginAckCommand extends Command<void> {
  PluginAckCommand({required this.plugins, required this.write}) {
    argParser
      ..addOption('project', defaultsTo: '.', help: 'Flutter project folder.')
      ..addFlag('json', negatable: false, help: 'Print one JSON object.');
  }

  final ProjectPlugins plugins;
  final void Function(String) write;

  @override
  String get name => 'ack';

  @override
  String get description =>
      'Mark the Package.swift draft of a plugin as reviewed.';

  @override
  String get invocation => 'xcross plugin ack <plugin> [--project <dir>]';

  @override
  Future<void> run() async {
    final args = argResults!;
    if (args.rest.length != 1) usageException('Pass exactly one plugin name.');
    final name = args.rest.single;
    final project = args.option('project')!;
    try {
      final found = plugins.read(project).where((p) => p.name == name);
      if (found.isEmpty) {
        throw PluginFailure(
          'plugin.not_found',
          '$name is not an iOS plugin of this project.',
          'List them with: xcross plugin status',
        );
      }
      final paths = plugins.paths;
      final ledger = DraftLedger(
        plugins.fileSystem,
        paths,
        paths.join(project, 'xcross_overrides'),
      );
      final version = found.single.version;
      final done =
          ledger.acknowledge(name, version) || ledger.acknowledge(name, null);
      if (!done) {
        throw PluginFailure(
          'plugin.no_draft',
          'xcross has no draft of $name waiting for review.',
          'Nothing to do: only drafts xcross wrote need it.',
        );
      }
      write(
        args.flag('json')
            ? '${jsonEncode({'v': 1, 'type': 'plugin_ack', 'plugin': name})}\n'
            : '✔ $name marked as reviewed.\n',
      );
    } on PluginFailure catch (failure) {
      throw failure.toCliError();
    }
  }
}
