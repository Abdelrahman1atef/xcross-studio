import 'dart:io';

import 'package:meta/meta.dart';
import 'package:path/path.dart' as p;

/// Regenerates `lib/src/host/windows/setup/windows_setup_scripts.g.dart`
/// from the repository's `setup/*.ps1`, which xcross compiles in so
/// `xcross setup` runs them without downloading anything.
///
/// Run from `packages/xcross` after changing a script:
///
///     dart run tool/generate_setup_scripts.dart
///
/// `test/setup/embedded_setup_scripts_test.dart` fails while the generated
/// file and the scripts differ.
void main() {
  final package = p.dirname(p.dirname(p.fromUri(Platform.script)));
  final output = File(p.join(package, generatedSetupScriptsPath));
  output.writeAsStringSync(
    renderSetupScripts(readSetupScripts(setupScriptsDirectory(package))),
  );
  stdout.writeln('Wrote ${output.path}');
}

/// The generated file, relative to `packages/xcross`.
@internal
const generatedSetupScriptsPath =
    'lib/src/host/windows/setup/windows_setup_scripts.g.dart';

/// The repository's `setup/` folder, from the `packages/xcross` folder.
@internal
String setupScriptsDirectory(String package) =>
    p.normalize(p.join(package, '..', '..', 'setup'));

/// Every `setup/*.ps1` by name without extension, sorted, with LF line
/// endings whatever the checkout uses.
@internal
Map<String, String> readSetupScripts(String directory) {
  final scripts =
      Directory(directory)
          .listSync()
          .whereType<File>()
          .where((file) => p.extension(file.path) == '.ps1')
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  return {
    for (final script in scripts)
      p.basenameWithoutExtension(script.path): script
          .readAsStringSync()
          .replaceAll('\r\n', '\n'),
  };
}

/// The Dart source holding [scripts] as constants, one escaped literal per
/// line so the text does not depend on how git checks the file out.
@internal
String renderSetupScripts(Map<String, String> scripts) {
  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/generate_setup_scripts.dart from setup/*.ps1.',
    )
    ..writeln(
      '// Do not edit; after changing a script run, in packages/xcross:',
    )
    ..writeln('//   dart run tool/generate_setup_scripts.dart')
    ..writeln("import 'package:meta/meta.dart';")
    ..writeln()
    ..writeln(
      '/// The built-in Windows setup scripts by name (`setup/<name>.ps1`),',
    )
    ..writeln('/// compiled into xcross.')
    ..writeln('@internal')
    ..writeln('const windowsSetupScripts = <String, String>{');
  for (final name in scripts.keys) {
    out.writeln("  '$name': _${_identifier(name)},");
  }
  out.writeln('};');
  for (final MapEntry(key: name, value: text) in scripts.entries) {
    out
      ..writeln()
      ..writeln('const _${_identifier(name)} =');
    final lines = text.split('\n');
    // A trailing newline leaves an empty last element, already covered by
    // the `\n` of the line before it.
    if (lines.length > 1 && lines.last.isEmpty) lines.removeLast();
    for (var i = 0; i < lines.length; i++) {
      final newline = i < lines.length - 1 || text.endsWith('\n');
      out.write("    '${_escape(lines[i])}${newline ? r'\n' : ''}'");
      out.writeln(i == lines.length - 1 ? ';' : '');
    }
  }
  return out.toString();
}

String _identifier(String name) => name.replaceAll(RegExp('[^A-Za-z0-9]'), '_');

String _escape(String line) {
  final out = StringBuffer();
  for (final rune in line.runes) {
    switch (rune) {
      case 0x5C: // \
        out.write(r'\\');
      case 0x27: // '
        out.write(r"\'");
      case 0x24: // $
        out.write(r'\$');
      case 0x09: // tab
        out.write(r'\t');
      case final code when code < 0x20 || code > 0x7E:
        out.write('\\u{${code.toRadixString(16)}}');
      default:
        out.writeCharCode(rune);
    }
  }
  return out.toString();
}
